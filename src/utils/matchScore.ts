import type { Resume } from "src/types/resume"
import type { TailoredResume } from "src/types/jobs"
import { diffLines, diffSet } from "src/utils/diff"

export interface MatchScore {
  current: number // 0-100, based only on what's actually accepted right now
  potential: number // 0-100, ceiling if every addressable suggestion were accepted
  total: number // addressable + unaddressable item count, for "(N of M)" context
}

// Recounts everything a tailoring pass flagged — skills, highlights, title,
// summary, education — into one 0-100 coverage score, purely from data
// already generated by the last "Optimize" call (same diffs/review state
// the accept/reject checkboxes already use). No new API call.
//
// Every discrete suggestion is either "addressable" (something the
// candidate can accept: an added skill, an added highlight, a changed
// summary/title, or a met education requirement) or "unaddressable"
// (missingKeywords, or an unmet education requirement — nothing to accept,
// ever). `current` counts only what's accepted in `review` right now;
// `potential` counts every addressable item, i.e. the ceiling.
export function computeMatchScore(tailored: TailoredResume, resume: Resume): MatchScore {
  const review = tailored.review
  let addressable = 0
  let accepted = 0
  let unaddressable = tailored.missingKeywords.length

  const baseSummary = (resume.basics.summary ?? "").trim()
  if (tailored.summary.trim() && tailored.summary.trim() !== baseSummary) {
    addressable++
    if (review?.summaryAccepted) accepted++
  }

  const baseTitle = (resume.basics.title ?? "").trim()
  if (tailored.title?.trim() && tailored.title.trim() !== baseTitle) {
    addressable++
    if (review?.titleAccepted) accepted++
  }

  for (const job of resume.work) {
    const tw = tailored.work.find((w) => w.id === job.id)
    if (!tw) continue
    const entryReview = review?.work.find((w) => w.id === job.id)

    if (tw.title?.trim() && tw.title.trim() !== job.position.trim()) {
      addressable++
      if (entryReview?.titleAccepted) accepted++
    }

    const addedHighlights = diffLines(job.highlights, tw.highlights).filter(
      (op) => op.type === "added",
    ).length
    addressable += addedHighlights
    accepted += entryReview?.acceptedAdds.length ?? 0
  }

  for (const group of resume.skills) {
    const ts = tailored.skills?.find((s) => s.id === group.id)
    if (!ts) continue
    const groupReview = review?.skills.find((s) => s.id === group.id)
    const addedSkills = diffSet(group.items, ts.items).filter(
      (op) => op.type === "added",
    ).length
    addressable += addedSkills
    accepted += groupReview?.acceptedAdds.length ?? 0
  }

  if (tailored.educationMatch) {
    if (tailored.educationMatch.met) {
      addressable++
      accepted++
    } else {
      unaddressable++
    }
  }

  const total = addressable + unaddressable
  if (total === 0) return { current: 100, potential: 100, total: 0 }

  return {
    current: Math.round((accepted / total) * 100),
    potential: Math.round((addressable / total) * 100),
    total,
  }
}
